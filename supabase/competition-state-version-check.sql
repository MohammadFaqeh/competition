-- تخفيف استهلاك الداتا/الجهاز أثناء الاستطلاع الدوري: كل حساب إدارة/مشرف يستطلع كل 9 ثوانٍ
-- (كل لجنة أيضاً)، وكان كل استطلاع يُنزّل كامل competition_state.payload (كل المتسابقين
-- والسحوبات، مئات العناصر) عبر الشبكة لمجرد التأكد "هل تغيّر شي؟" — حتى لو الجواب لا بأغلب
-- الأحيان (لا شيء تغيّر فعلياً خلال 9 ثوانٍ عادةً). هذا استهلاك بيانات وذاكرة متكرر بلا داعٍ،
-- خصوصاً على أجهزة اللجان (غالباً هواتف/أجهزة أضعف وشبكة أضعف أيام الامتحان).
--
-- الحل: دالة صغيرة جداً تُرجع فقط توقيت آخر تعديل (لا بيانات إطلاقاً)، يُستدعى الاستطلاع
-- الدوري بها أولاً — إذا لم يتغيّر التوقيت عن آخر مرة معروفة محلياً، يتوقف هناك دون تنزيل
-- الحمولة الكاملة إطلاقاً. لا تعدّل أو تلمس أي دالة موجودة (إضافة صرفة بلا أي مجازفة على
-- منطق معتمد)، ولا تكشف أي بيانات حساسة (توقيت فقط، لا مشاركين ولا نتائج).
-- نفّذه من SQL Editor بعد كل ملفات supabase/*.sql الحالية.

create or replace function public.competition_state_version()
returns timestamptz language sql stable security definer set search_path=public
as $$
  select updated_at from public.competition_state where id=1;
$$;

grant execute on function public.competition_state_version() to anon,authenticated;
